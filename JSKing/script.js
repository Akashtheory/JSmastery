// Project := Marksheet // grades(A,B,C,D, Grace & Fail)

let hindi = 58;

let english = 65;

let maths = 71;

let science = 90;

let Social = 65;

let total = hindi + english + maths + science + Social;


let percentage = (total /500)*100;


console.log("Total Marks:"+ total);

console.log("Percentage:" + percentage + "%");


// Grades

if(percentage >= 85 && percentage<=100){
    console.log("Grade A+");
    
}
else if(percentage >= 75 && percentage <= 85){
    console.log("Grade A");
    
}
else if(percentage >= 60 && percentage <= 75){
    console.log("Grade B");
    
}
else if(percentage >= 45 && percentage <= 60){
    console.log("Grade C");
    
}
else if(percentage >= 33 && percentage <= 45){
    console.log("Grade D");
    
}
else if(percentage >= 29 && percentage <= 33){
    console.log("Grace mili hai");
    
}
else if(percentage >= 0 && percentage <= 28){
    console.log("Fail Ho Gya");
    
}
else{
    console.log("Absent Fail Ho Gya");
    
}
























 










